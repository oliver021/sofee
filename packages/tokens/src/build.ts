#!/usr/bin/env node
/**
 * Generates `generated/tokens.css` from the typed palette data in
 * palettes.ts. This is the one build step in the repo that turns *data*
 * into *CSS custom properties* (repo layout: "palettes as data -> generated
 * CSS custom properties + TS types") — everything else consumes the TS
 * source directly. Re-run with `npm run build -w @sofee/tokens`; it is also
 * wired into the root `postinstall` and into apps/web's `predev`/`prebuild`.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { palettes, paletteIds, DEFAULT_PALETTE, semanticColors } from './palettes.js';
import { derivedTokens, hexToRgb } from './derive.js';
import { baseCss } from './css-base.js';
import type { Palette } from './types.js';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, '..', 'generated');
const outFile = join(outDir, 'tokens.css');

const DEFAULT_DOT_MASK = 'radial-gradient(120% 120% at 50% 35%, #000 55%, transparent 100%)';
const FLAT_DOT_MASK = 'none';

/** §3 formula, applied literally: a long soft falloff, never a hard-stop dot. */
function dotGradient(palette: Palette): string {
  const [r, g, b] = hexToRgb(palette.dot.color);
  const { radiusPx, alphaStart, alphaEnd } = palette.dot;
  return `radial-gradient(circle ${radiusPx}px at center, rgba(${r}, ${g}, ${b}, ${alphaStart}) 0%, rgba(${r}, ${g}, ${b}, ${alphaEnd}) 46%, rgba(${r}, ${g}, ${b}, 0) 100%)`;
}

/** §2 "Extra gradient layer" for Hacker Terminal — derived from its own accent, not a magic literal. */
function scanlineFor(palette: Palette): string {
  if (!palette.scanline) return 'none';
  const [r, g, b] = hexToRgb(palette.colors.acc);
  return `repeating-linear-gradient(180deg, rgba(${r}, ${g}, ${b}, 0.026) 0 1px, transparent 1px 4px)`;
}

function ruleFor(palette: Palette, selector: string): string {
  const derived = derivedTokens(palette);
  const semantic = semanticColors[palette.scheme];
  const lines: string[] = [
    `--p-bg: ${palette.colors.bg};`,
    `--p-surf: ${palette.colors.surf};`,
    `--p-ink: ${palette.colors.ink};`,
    `--p-mut: ${palette.colors.mut};`,
    `--p-acc: ${palette.colors.acc};`,
    `--p-acc2: ${palette.colors.acc2};`,
  ];
  for (const [name, value] of Object.entries(derived)) {
    lines.push(`${name}: ${value};`);
  }
  lines.push(
    `--p-display: ${palette.display.cssFamily};`,
    `--p-dot: ${dotGradient(palette)};`,
    `--p-dot-size: ${palette.dot.pitchPx}px;`,
    `--p-dot-mask: ${palette.dotMaskFlat ? FLAT_DOT_MASK : DEFAULT_DOT_MASK};`,
    `--p-grad: ${palette.gradientCss};`,
    `--p-blend: ${palette.blend ?? 'normal'};`,
    `--p-scanline: ${scanlineFor(palette)};`,
    `--sem-success: ${semantic.success};`,
    `--sem-success-ink: ${semantic.successInk};`,
    `--sem-warning: ${semantic.warning};`,
    `--sem-warning-ink: ${semantic.warningInk};`,
    `--sem-critical: ${semantic.critical};`,
    `--sem-critical-ink: ${semantic.criticalInk};`,
  );
  return `${selector} {\n  ${lines.join('\n  ')}\n}\n`;
}

async function build(): Promise<void> {
  const defaultPalette = palettes[DEFAULT_PALETTE];
  const parts: string[] = [
    '/* AUTO-GENERATED by packages/tokens/src/build.ts — do not hand-edit.',
    ' * Source of truth: packages/tokens/src/palettes.ts (design-system.md §1-§4). */',
    baseCss.trim(),
    '',
    '/* Default values applied before data-palette is set (avoids a flash of',
    '   unstyled content on first paint) — mirrors the default palette, nocturne. */',
    ruleFor(defaultPalette, ':root'),
  ];

  for (const id of paletteIds) {
    const palette = palettes[id];
    if (!palette) continue;
    parts.push(ruleFor(palette, `[data-palette='${id}']`));
  }

  await mkdir(outDir, { recursive: true });
  await writeFile(outFile, `${parts.join('\n')}\n`, 'utf8');
  console.log(`[@sofee/tokens] wrote ${outFile}`);
}

await build();
